"""
Author: Parikshith Venkataraghavan
Purpose: builds the embedded web pages (src/web/*_html.h) from the real
         HTML/CSS/JS files in web/. The firmware serves each page as one
         self-contained string, so this script inlines the page's own
         stylesheet and script and turns the {{NAME}} placeholders into the
         config.h macros of the same name.

    python tools/embed_web.py          rebuild every header that changed
    python tools/embed_web.py --check  only check, exit 1 if a header is
                                       out of date (test/run_tests.sh does this)

Rules for the files in web/<page>/:
    - index.html is the page. <link rel="stylesheet" href="x.css"> and
      <script src="x.js"></script> must name files in the same folder, and
      are replaced by their contents. nothing else is fetched (the setup AP
      has no internet, so no CDNs)
    - {{NAME}} is replaced by the config.h #define NAME: a string macro goes
      in as is, a number macro as its digits. a name that isn't in config.h is
      an error, so the page can't drift from the firmware. in JS, keep them
      inside quotes ('{{API_STATE_PATH}}', Number('{{WEB_POLL_MS}}')) so the
      file stays valid JavaScript
    - never edit src/web/*_html.h by hand, the next run overwrites them
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(ROOT, "src", "config.h")

#source folder, generated header, C symbol, what it is (for the header comment)
PAGES = [
    ("web/control", "src/web/index_html.h", "INDEX_HTML",
     "the web control page, served by RestApi (comms/rest_api.h) at WEB_CONTROL_PATH and at / outside setup mode"),
    ("web/setup", "src/web/provisioning_html.h", "PROVISIONING_HTML",
     "the Wi-Fi setup page, served by Provisioning (comms/provisioning.h) at / in setup (AP) mode"),
]

#the raw string delimiter in the header, so the page can contain anything but this
DELIM = "HTML"

LINK_RE = re.compile(r'<link rel="stylesheet" href="([^"]+)">')
SCRIPT_RE = re.compile(r'<script src="([^"]+)"></script>')
PLACEHOLDER_RE = re.compile(r"\{\{([A-Z0-9_]+)\}\}")
DEFINE_RE = re.compile(r"^\s*#define\s+([A-Z0-9_]+)\s+(\S.*?)\s*(//.*)?$")


class EmbedError(Exception):
    pass


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def config_macros():
    """NAME -> True for a string macro, False for a number"""
    macros = {}
    for line in read(CONFIG).splitlines():
        m = DEFINE_RE.match(line)
        if m:
            macros[m.group(1)] = m.group(2).startswith('"')
    return macros


def inline(page_dir, html):
    def file_in(regex, wrap):
        def sub(m):
            name = m.group(1)
            path = os.path.join(page_dir, name)
            if "/" in name or "\\" in name or not os.path.isfile(path):
                raise EmbedError("%s: %s must be a file next to index.html" % (page_dir, name))
            return wrap % read(path)
        return regex.sub(sub, html)

    html = file_in(LINK_RE, "<style>\n%s</style>")
    html = file_in(SCRIPT_RE, "<script>\n%s</script>")
    for tag in ("<link", "<script src"):
        if tag in html:
            raise EmbedError("%s: a %s the script doesn't understand is left in the page" % (page_dir, tag))
    return html


def to_cpp(page_dir, html, macros):
    """the page as the pieces of one C++ string: raw strings and config.h macros"""
    if ")%s\"" % DELIM in html:
        raise EmbedError('%s: the page contains )%s", which would end the raw string' % (page_dir, DELIM))
    out = []
    pos = 0
    for m in PLACEHOLDER_RE.finditer(html):
        name = m.group(1)
        if name not in macros:
            raise EmbedError("%s: {{%s}} is not a #define in src/config.h" % (page_dir, name))
        out.append(html[pos:m.start()])
        out.append(")%s\" %s R\"%s(" % (DELIM, name if macros[name] else "WEB_HTML_STR(%s)" % name, DELIM))
        pos = m.end()
    out.append(html[pos:])
    return "".join(out)


def header(page_dir, header_path, symbol, what, macros):
    html = inline(os.path.join(ROOT, page_dir), read(os.path.join(ROOT, page_dir, "index.html")))
    guard = os.path.basename(header_path).replace(".", "_").upper()
    return (
        "/**************************************************************************\n"
        "*   Author: Parikshith Venkataraghavan\n"
        "*   Purpose: %s\n"
        "**************************************************************************/\n"
        "\n"
        "/*\n"
        "    GENERATED by tools/embed_web.py from %s/, do not edit.\n"
        "    Change the files there and run: python tools/embed_web.py\n"
        "    How the page works: web/README.md\n"
        "*/\n"
        "\n"
        "#ifndef %s\n"
        "#define %s\n"
        "\n"
        "#include <Arduino.h>\n"
        "#include \"../config.h\"\n"
        "\n"
        "//puts a number from config.h into the page\n"
        "#ifndef WEB_HTML_STR\n"
        "#define WEB_HTML_STR_(x) #x\n"
        "#define WEB_HTML_STR(x) WEB_HTML_STR_(x)\n"
        "#endif\n"
        "\n"
        "static const char %s[] PROGMEM = R\"%s(%s)%s\";\n"
        "\n"
        "#endif\n"
    ) % (what, page_dir, guard, guard, symbol, DELIM, to_cpp(page_dir, html, macros), DELIM)


def main():
    check = "--check" in sys.argv[1:]
    macros = config_macros()
    stale = []
    for page_dir, header_path, symbol, what in PAGES:
        try:
            text = header(page_dir, header_path, symbol, what, macros)
        except EmbedError as e:
            print("embed_web: %s" % e)
            return 1
        path = os.path.join(ROOT, header_path)
        old = read(path) if os.path.isfile(path) else None
        #line endings don't count (git may check the header out with CRLF)
        if old is not None and old.replace("\r\n", "\n") == text:
            continue
        if check:
            stale.append(header_path)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("embed_web: wrote %s" % header_path)
    if stale:
        print("embed_web: out of date: %s. run: python tools/embed_web.py" % ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
